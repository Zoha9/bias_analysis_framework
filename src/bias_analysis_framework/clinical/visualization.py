from __future__ import annotations

import math
import textwrap
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def generate_clinical_distribution_figures(
    count_tables: dict[str, pd.DataFrame],
    output_dir: str | Path,
    config: dict[str, Any],
) -> list[Path]:
    """Generate Step 1 clinical distribution/count figures.

    This module visualizes the count tables generated by
    bias_analysis_framework.clinical.counts.

    Generated figure groups:
    - target class counts
    - bias factor subgroup counts
    - age counts
    - tissue source site counts
    - bias factor by target class count heatmap
    """
    output_dir = Path(output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []

    target_counts = count_tables.get("target_class_counts")
    if target_counts is not None and not target_counts.empty:
        written.extend(
            plot_target_class_counts(
                target_counts=target_counts,
                output_dir=output_dir / "target_class_counts",
            )
        )

    bias_counts = count_tables.get("bias_factor_subgroup_counts")
    if bias_counts is not None and not bias_counts.empty:
        written.extend(
            plot_bias_factor_subgroup_counts(
                bias_counts=bias_counts,
                output_dir=output_dir / "bias_factor_subgroup_counts",
            )
        )

    age_counts = count_tables.get("age_counts")
    if age_counts is not None and not age_counts.empty:
        written.append(
            plot_age_counts(
                age_counts=age_counts,
                output_path=output_dir / "age_counts" / "age_counts.png",
            )
        )

    tissue_counts = count_tables.get("tissue_source_site_counts")
    if tissue_counts is not None and not tissue_counts.empty:
        written.append(
            plot_tissue_source_site_counts(
                tissue_counts=tissue_counts,
                output_path=output_dir / "tissue_source_site_counts" / "tissue_source_site_counts.png",
            )
        )

    cross_counts = count_tables.get("bias_factor_by_target_class_counts")
    if cross_counts is not None and not cross_counts.empty:
        written.append(
            plot_bias_factor_by_target_class_heatmap(
                cross_counts=cross_counts,
                output_path=(
                    output_dir
                    / "bias_factor_by_target_class_counts"
                    / "bias_factor_by_target_class_counts_heatmap.png"
                ),
                config=config,
            )
        )

    return [path for path in written if path is not None]


def plot_target_class_counts(
    target_counts: pd.DataFrame,
    output_dir: str | Path,
) -> list[Path]:
    """Plot one class-count bar chart per target biomarker."""
    output_dir = Path(output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    required = {"target", "class", "count"}
    validate_columns(target_counts, required, "target_counts")

    written: list[Path] = []

    for target_name, target_df in target_counts.groupby("target", sort=False):
        plot_df = (
            target_df.sort_values("count", ascending=False)
            .loc[:, ["class", "count"]]
            .reset_index(drop=True)
        )

        output_path = output_dir / f"{safe_filename(target_name)}__class_counts.png"

        fig_width = max(7, min(18, 1.2 * len(plot_df) + 4))
        fig_height = 5

        fig, ax = plt.subplots(figsize=(fig_width, fig_height))
        ax.bar(plot_df["class"].astype(str), plot_df["count"].astype(int))

        ax.set_title(f"{target_name}: class counts")
        ax.set_xlabel("Class")
        ax.set_ylabel("Count")

        rotate_x_labels(ax, labels=plot_df["class"].astype(str).tolist())
        annotate_bars(ax)

        save_figure(fig, output_path)
        written.append(output_path)

    return written


def plot_bias_factor_subgroup_counts(
    bias_counts: pd.DataFrame,
    output_dir: str | Path,
) -> list[Path]:
    """Plot one subgroup-count bar chart per bias factor."""
    output_dir = Path(output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    required = {"bias_factor", "subgroup", "count"}
    validate_columns(bias_counts, required, "bias_counts")

    written: list[Path] = []

    for factor_name, factor_df in bias_counts.groupby("bias_factor", sort=False):
        plot_df = (
            factor_df.sort_values("count", ascending=False)
            .loc[:, ["subgroup", "count"]]
            .reset_index(drop=True)
        )

        output_path = output_dir / f"{safe_filename(factor_name)}__subgroup_counts.png"

        fig_width = max(8, min(22, 1.0 * len(plot_df) + 5))
        fig_height = max(5, min(14, 0.45 * len(plot_df) + 4))

        fig, ax = plt.subplots(figsize=(fig_width, fig_height))

        if len(plot_df) >= 8:
            ax.barh(plot_df["subgroup"].astype(str), plot_df["count"].astype(int))
            ax.invert_yaxis()
            ax.set_xlabel("Count")
            ax.set_ylabel("Subgroup")
            annotate_horizontal_bars(ax)
        else:
            ax.bar(plot_df["subgroup"].astype(str), plot_df["count"].astype(int))
            ax.set_xlabel("Subgroup")
            ax.set_ylabel("Count")
            rotate_x_labels(ax, labels=plot_df["subgroup"].astype(str).tolist())
            annotate_bars(ax)

        ax.set_title(f"{factor_name}: subgroup counts")

        save_figure(fig, output_path)
        written.append(output_path)

    return written


def plot_age_counts(
    age_counts: pd.DataFrame,
    output_path: str | Path,
) -> Path:
    """Plot age count distribution."""
    output_path = Path(output_path).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    required = {"age", "count"}
    validate_columns(age_counts, required, "age_counts")

    plot_df = age_counts.sort_values("age").reset_index(drop=True)

    fig_width = max(9, min(24, 0.35 * len(plot_df) + 5))
    fig_height = 5

    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    ax.bar(plot_df["age"].astype(str), plot_df["count"].astype(int))

    age_column = (
        str(plot_df["age_column"].iloc[0])
        if "age_column" in plot_df.columns and not plot_df.empty
        else "Age"
    )

    ax.set_title(f"{age_column}: age counts")
    ax.set_xlabel(age_column)
    ax.set_ylabel("Count")

    rotate_x_labels(ax, labels=plot_df["age"].astype(str).tolist(), force_rotation=True)
    annotate_bars(ax, max_bars=40)

    save_figure(fig, output_path)
    return output_path


