def plot_bias_factor_by_target_class_heatmap(
    cross_counts: pd.DataFrame,
    output_path: str | Path,
    config: dict[str, Any],
) -> Path:
    """Plot heatmap of bias-factor subgroup counts by target class.

    Input table columns:
    - bias_factor
    - subgroup
    - target
    - class
    - count
    """
    output_path = Path(output_path).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    required = {"bias_factor", "subgroup", "target", "class", "count"}
    validate_columns(cross_counts, required, "cross_counts")

    plot_df = cross_counts.copy()
    plot_df["row_label"] = (
        plot_df["bias_factor"].astype(str)
        + ": "
        + plot_df["subgroup"].astype(str)
    )
    plot_df["column_label"] = (
        plot_df["target"].astype(str)
        + " ["
        + plot_df["class"].astype(str)
        + "]"
    )

    matrix = (
        plot_df.pivot_table(
            index="row_label",
            columns="column_label",
            values="count",
            aggfunc="sum",
            fill_value=0,
        )
        .astype(int)
    )

    matrix = order_heatmap_matrix(matrix, cross_counts, config)

    if matrix.empty:
        return output_path

    fig_width = max(10, min(34, 0.75 * matrix.shape[1] + 6))
    fig_height = max(6, min(28, 0.38 * matrix.shape[0] + 4))

    fig, ax = plt.subplots(figsize=(fig_width, fig_height))

    masked = matrix.replace(0, np.nan)
    image = ax.imshow(masked.values, aspect="auto", interpolation="nearest")

    colorbar = fig.colorbar(image, ax=ax)
    colorbar.set_label("Count")

    ax.set_xticks(np.arange(matrix.shape[1]))
    ax.set_yticks(np.arange(matrix.shape[0]))

    ax.set_xticklabels(
        [wrap_label(label, width=16) for label in matrix.columns],
        rotation=45,
        ha="right",
        fontsize=8,
    )
    ax.set_yticklabels(
        [wrap_label(label, width=28) for label in matrix.index],
        fontsize=8,
    )

    ax.set_xlabel("Target biomarker class")
    ax.set_ylabel("Bias factor subgroup")
    ax.set_title("Counts by bias factor subgroup and target class")

    add_heatmap_grid(ax, matrix)
    annotate_heatmap_counts(ax, matrix)

    fig.tight_layout()

    save_figure(fig, output_path)
    return output_path


def order_heatmap_matrix(
    matrix: pd.DataFrame,
    cross_counts: pd.DataFrame,
    config: dict[str, Any],
) -> pd.DataFrame:
    """Order rows and columns using config order where possible."""
    target_order = []
    for target in config.get("targets", []):
        target_name = target.get("name")
        if not target_name:
            continue

        if target.get("labels"):
            labels = target["labels"]
        elif target.get("negative_label") is not None and target.get("positive_label") is not None:
            labels = [target["negative_label"], target["positive_label"]]
        else:
            labels = (
                cross_counts.loc[cross_counts["target"] == target_name, "class"]
                .dropna()
                .astype(str)
                .drop_duplicates()
                .tolist()
            )

        for label in labels:
            target_order.append(f"{target_name} [{label}]")

    existing_columns = [column for column in target_order if column in matrix.columns]
    remaining_columns = [column for column in matrix.columns if column not in existing_columns]
    matrix = matrix.loc[:, existing_columns + remaining_columns]

    row_order = []
    for factor in config.get("bias_factors", []):
        factor_name = factor.get("name")
        if not factor_name:
            continue

        factor_rows = [row for row in matrix.index if str(row).startswith(f"{factor_name}: ")]
        row_order.extend(sorted(factor_rows))

    existing_rows = [row for row in row_order if row in matrix.index]
    remaining_rows = [row for row in matrix.index if row not in existing_rows]

    return matrix.loc[existing_rows + remaining_rows, :]


def validate_columns(
    dataframe: pd.DataFrame,
    required_columns: set[str],
    table_name: str,
) -> None:
    """Validate that a dataframe contains required columns."""
    missing = sorted(required_columns - set(dataframe.columns))
    if missing:
        raise ValueError(f"{table_name} is missing required columns: {missing}")


def annotate_bars(
    ax: plt.Axes,
    max_bars: int = 25,
) -> None:
    """Annotate vertical bars with counts."""
    bars = ax.patches

    if len(bars) > max_bars:
        return

    for bar in bars:
        height = bar.get_height()
        if not math.isfinite(height):
            continue

        ax.annotate(
            f"{int(height):,}",
            xy=(bar.get_x() + bar.get_width() / 2, height),
            xytext=(0, 3),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=8,
        )


def annotate_horizontal_bars(
    ax: plt.Axes,
    max_bars: int = 40,
) -> None:
    """Annotate horizontal bars with counts."""
    bars = ax.patches

    if len(bars) > max_bars:
        return

    for bar in bars:
        width = bar.get_width()
        if not math.isfinite(width):
            continue

        ax.annotate(
            f"{int(width):,}",
            xy=(width, bar.get_y() + bar.get_height() / 2),
            xytext=(4, 0),
            textcoords="offset points",
            ha="left",
            va="center",
            fontsize=8,
        )


def annotate_heatmap_counts(
    ax: plt.Axes,
    matrix: pd.DataFrame,
    max_cells: int = 250,
) -> None:
    """Annotate heatmap cells with integer counts."""
    n_rows, n_cols = matrix.shape

    if n_rows * n_cols > max_cells:
        return

    for row_idx in range(n_rows):
        for col_idx in range(n_cols):
            value = matrix.iat[row_idx, col_idx]
            if pd.isna(value) or value == 0:
                continue

            ax.text(
                col_idx,
                row_idx,
                f"{int(value):,}",
                ha="center",
                va="center",
                fontsize=7,
            )


def add_heatmap_grid(
    ax: plt.Axes,
    matrix: pd.DataFrame,
) -> None:
    """Add subtle grid lines to heatmap cells."""
    ax.set_xticks(np.arange(-0.5, matrix.shape[1], 1), minor=True)
    ax.set_yticks(np.arange(-0.5, matrix.shape[0], 1), minor=True)
    ax.grid(which="minor", linestyle="-", linewidth=0.25)
    ax.tick_params(which="minor", bottom=False, left=False)


def rotate_x_labels(
    ax: plt.Axes,
    labels: list[str],
    force_rotation: bool = False,
) -> None:
    """Rotate x-axis labels when labels are long or numerous."""
    max_label_length = max((len(str(label)) for label in labels), default=0)

    if force_rotation or len(labels) > 5 or max_label_length > 12:
        ax.tick_params(axis="x", labelrotation=45)
        for label in ax.get_xticklabels():
            label.set_horizontalalignment("right")


def wrap_label(
    label: object,
    width: int = 18,
) -> str:
    """Wrap long plot labels."""
    return "\n".join(
        textwrap.wrap(
            str(label),
            width=width,
            break_long_words=False,
            replace_whitespace=False,
        )
    )


def safe_filename(value: object) -> str:
    """Create filesystem-safe filename stem."""
    text = str(value).strip()

    for char in [" ", "/", "\\", ":", ";", ",", "|", "(", ")", "[", "]", "{", "}"]:
        text = text.replace(char, "_")

    while "__" in text:
        text = text.replace("__", "_")

    text = text.strip("_")
    return text or "unnamed"


def save_figure(
    fig: plt.Figure,
    output_path: str | Path,
) -> None:
    """Save and close a matplotlib figure."""
    output_path = Path(output_path).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    fig.tight_layout()
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)